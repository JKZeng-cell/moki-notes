import { fileURLToPath } from 'node:url';
import { createApp } from './app.js';
import { NotesStore } from './store.js';
import { dataPath } from './paths.js';
const store = new NotesStore(dataPath());
store.ensureDemo();
const app = await createApp(store, { webRoot: fileURLToPath(new URL('../web', import.meta.url)) });
await app.listen({ host: '127.0.0.1', port: Number(process.env.MOKI_NOTES_PORT ?? 4331) });
console.log(`MOKI便签 http://127.0.0.1:${process.env.MOKI_NOTES_PORT ?? 4331}`);
for (const signal of ['SIGINT', 'SIGTERM'] as const) process.on(signal, () => { void app.close().then(() => store.close()); });
